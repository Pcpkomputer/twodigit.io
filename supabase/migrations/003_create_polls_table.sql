-- 1. Table for Poll Sessions
CREATE TABLE IF NOT EXISTS public.polls (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    options JSONB NOT NULL,
    total_votes INT DEFAULT 0 NOT NULL,
    status TEXT DEFAULT 'active' NOT NULL, -- 'active', 'ended', 'archived'
    winner JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    ended_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_polls_status ON public.polls(status);
CREATE INDEX IF NOT EXISTS idx_polls_created_at ON public.polls(created_at);

-- 2. Table for Individual User Votes (Atomic duplicate prevention)
CREATE TABLE IF NOT EXISTS public.poll_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id TEXT NOT NULL REFERENCES public.polls(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    option_index INT NOT NULL,
    nickname TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    CONSTRAINT unique_poll_user UNIQUE (poll_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_poll_votes_poll_user ON public.poll_votes(poll_id, user_id);
CREATE INDEX IF NOT EXISTS idx_poll_votes_poll_id ON public.poll_votes(poll_id);

-- 3. Row Level Security (RLS)
ALTER TABLE public.polls ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.poll_votes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access to polls" 
ON public.polls FOR SELECT 
USING (true);

CREATE POLICY "Allow service role full access to polls" 
ON public.polls FOR ALL 
TO service_role 
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow public read access to poll_votes" 
ON public.poll_votes FOR SELECT 
USING (true);

CREATE POLICY "Allow service role full access to poll_votes" 
ON public.poll_votes FOR ALL 
TO service_role 
USING (true)
WITH CHECK (true);
